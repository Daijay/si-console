"""Subset the open fonts to the characters the mockups use.

Usage: python fonts.py <folder with the source .ttf files>
Sources: github.com/google/fonts, ofl/b612, b612mono, notosanssc,
ibmplexmono, instrumentsans. Needs fonttools and brotli.
On the Pi, live transcript text outside the subset falls back to the
system Noto Sans CJK SC (apt install fonts-noto-cjk).
"""
import sys
from pathlib import Path

from fontTools import subset

HERE = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1])
OUT = HERE / "fonts"

FACES = [  # family, source file, output name, weight
    ("SI Deck", "B612-Regular.ttf", "b612-400", "400"),
    ("SI Deck", "B612-Bold.ttf", "b612-700", "700"),
    ("SI Sans SC", "NotoSansSC[wght].ttf", "notosanssc-var", "100 900"),
    # SI Term: tool calls, and direction study B. SI Product: study C only.
    ("SI Term", "IBMPlexMono-Regular.ttf", "plexmono-400", "400"),
    ("SI Term", "IBMPlexMono-Bold.ttf", "plexmono-700", "700"),
    ("SI Product", "InstrumentSans[wdth,wght].ttf", "instrument-var", "400 700"),
]

text = "".join(chr(c) for c in range(32, 127)) + "…·’‘“”、。，！？：；（）％¥×✓→"
files = [HERE.parent / "strings.json"] + [
    p for pat in ("directions/*.html", "js/*.js", "*.html") for p in HERE.glob(pat)
]
for path in files:
    text += path.read_text(encoding="utf-8")
chars = "".join(sorted({c for c in text if c >= " "}))

css = ["/* Generated by tools/fonts.py. All fonts are SIL OFL 1.1, see OFL-*.txt. */"]
for family, source, name, weight in FACES:
    opts = subset.Options(flavor="woff2", layout_features=["*"])
    font = subset.load_font(str(SRC / source), opts)
    sub = subset.Subsetter(opts)
    sub.populate(text=chars)
    sub.subset(font)
    subset.save_font(font, str(OUT / f"{name}.woff2"), opts)
    local = ',local("Noto Sans CJK SC")' if family == "SI Sans SC" else ""
    css.append(
        f'@font-face{{font-family:"{family}";src:url("{name}.woff2") format("woff2"){local};'
        f"font-weight:{weight};font-display:block}}"
    )
(OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
print(len(chars), "characters subset into", len(FACES), "faces")
