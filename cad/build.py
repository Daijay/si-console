"""Build everything for SI Console Rev R5 (open frame) from params.py.

    python build.py                 build, check, write outputs, copy finals to ../blueprints/R5
    python build.py --no-render     skip the PNG renders (fast)
    python build.py --no-copy       do not copy finals into ../blueprints/R5

Exit status is 1 if any check fails (CHECKS.md says which).
"""
import datetime
import os
import re
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import params as P  # noqa: E402
import panels as pn  # noqa: E402
import parts as pt  # noqa: E402
import checks as ck  # noqa: E402
import outputs as out  # noqa: E402

OUT = out.OUT
REPO = os.path.dirname(HERE)


def read_params():
    """Parse params.py for (name, value text, comment, status) so docs always match the file."""
    rows = []
    pat = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*(.+?)\s+#\s*(.*)$")
    for line in open(os.path.join(HERE, "params.py"), encoding="utf8"):
        m = pat.match(line.rstrip("\n"))
        if not m:
            continue
        name, val, com = m.groups()
        st = "ASSUMED" if "ASSUMED" in com else "VERIFIED" if "VERIFIED" in com else "DESIGN" if "DESIGN" in com else "UNTAGGED"
        rows.append((name, val, com, st))
    return rows


def _desc(com):
    return re.sub(r"^ASSUMED\.?\s*", "", com).replace("|", "/")


def table(assumed):
    lines = ["| Parameter | Value | What it is |", "| --- | --- | --- |"]
    for name, val, com, st in assumed:
        lines.append(f"| `{name}` | `{val}` | {_desc(com)} |")
    return lines


def write_assumed(rows):
    assumed = [r for r in rows if r[3] == "ASSUMED"]
    lines = ["# ASSUMED dimensions: measure with calipers before cutting", "",
             f"Generated by build.py from params.py, Rev {P.REV}. Change a value in params.py and re-run to update.", ""] + table(assumed) + [""]
    open(os.path.join(OUT, "ASSUMED.md"), "w", encoding="utf8").write("\n".join(lines))
    return assumed


def update_readme_block(assumed):
    path = os.path.join(HERE, "README.md")
    if not os.path.exists(path):
        return
    txt = open(path, encoding="utf8").read()
    block = "\n".join(["<!-- ASSUMED:START (generated by build.py, do not edit by hand) -->", ""] + table(assumed) + ["", "<!-- ASSUMED:END -->"])
    open(path, "w", encoding="utf8").write(re.sub(r"<!-- ASSUMED:START.*?<!-- ASSUMED:END -->", lambda m: block, txt, flags=re.S))


def write_checks(results, sheets):
    ok = all(r.ok for r in results)
    L = [f"# CHECKS, SI Console Rev {P.REV}", "",
         f"Run {datetime.date.today().isoformat()} by `cad/build.py`. Overall: **{'ALL CHECKS PASSED' if ok else 'CHECKS FAILED'}**.", "",
         f"Laser sheets used: **{len(sheets)}** ({P.SHEET_W:g} x {P.SHEET_L:g} mm).", "", "| Result | Check |", "| --- | --- |"]
    for r in results:
        L.append(f"| {'PASS' if r.ok else '**FAIL**'} | {r.name} |")
    L.append("")
    for r in results:
        L.append(f"## {'PASS' if r.ok else 'FAIL'}: {r.name}")
        L.append("")
        for ln in r.lines:
            L.append(f"- {ln}")
        L.append("")
    L.append("## Nested layout")
    L.append("")
    for i, placed in enumerate(sheets, 1):
        L.append(f"- Sheet {i}: " + ", ".join(f"{n}{' (rotated)' if rot else ''}" for (n, key, rot, x, y, w, h) in placed))
    L.append("")
    open(os.path.join(OUT, "CHECKS.md"), "w", encoding="utf8").write("\n".join(L))
    return ok


def copy_finals():
    dst = os.path.join(REPO, "blueprints", P.REV)
    os.makedirs(dst, exist_ok=True)
    for sub in ("step", "dxf", "drawings", "renders"):
        s = os.path.join(OUT, sub)
        d = os.path.join(dst, sub)
        if os.path.isdir(d):
            shutil.rmtree(d)
        if os.path.isdir(s):
            shutil.copytree(s, d)
    for f in (f"si_console_assembly_{P.REV}.step", "CHECKS.md", "ASSUMED.md"):
        shutil.copy(os.path.join(OUT, f), os.path.join(dst, f))
    return dst


def main(argv):
    t0 = time.time()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    rows = read_params()
    untagged = [r[0] for r in rows if r[3] == "UNTAGGED"]
    if untagged:
        print("params.py has untagged parameters (need VERIFIED, ASSUMED or DESIGN):", untagged)
        return 2
    assumed = write_assumed(rows)
    update_readme_block(assumed)

    print("[1/6] building laser parts and components")
    panel_dict = pn.build_panels()
    parts = pt.all_parts(panel_dict)

    print("[2/6] running checks")
    results = ck.run_all(panel_dict, parts)

    print("[3/6] STEP")
    out.export_step(parts)

    print("[4/6] DXF laser files and nested layout")
    cuts = out.export_dxf(panel_dict)
    sheets = out.nest(panel_dict, cuts)
    out.export_nested(cuts, sheets)
    out.nest_preview(cuts, sheets)

    print("[5/6] dimensioned drawings")
    out.export_drawings(panel_dict)

    if "--no-render" not in argv:
        print("[6/6] renders")
        import render
        render.render_all(parts)
    else:
        print("[6/6] renders skipped")

    ok = write_checks(results, sheets)
    for r in results:
        print(("PASS  " if r.ok else "FAIL  ") + r.name)
        if not r.ok:
            for ln in r.lines:
                if ln.startswith("FAIL"):
                    print("      " + ln)
    print(f"Laser sheets: {len(sheets)}")
    if "--no-copy" not in argv:
        print("copied finals to", copy_finals())
    print(f"done in {time.time() - t0:.0f} s")
    if not ok:
        print("\n" + "!" * 70 + "\n  ONE OR MORE CHECKS FAILED. See cad/output/CHECKS.md\n" + "!" * 70)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
